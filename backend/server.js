async function executeStatements(connection, statements) {
  for (const statement of statements) {
    try {
      await connection.query(statement);
    } catch (err) {
      // Ignore errors for ALTER TABLE if column already exists (for migrations)
      if (statements === MIGRATION_STATEMENTS &&
        (err.code === 'ER_DUP_FIELDNAME' || err.message?.includes('Duplicate column name'))) {
        console.log('Column already exists, skipping migration...');
        continue;
      }
      throw err;
    }
  }
}

async function provisionDatabase() {
  const rootConnection = await mysqlPromise.createConnection({
    host: DB_HOST,
    user: ROOT_USER,
    password: ROOT_PASSWORD,
    multipleStatements: true
  });

  try {
    await rootConnection.query(
      `CREATE DATABASE IF NOT EXISTS \`${APP_DB_NAME}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci`
    );
    await rootConnection.query(`DROP USER IF EXISTS '${APP_DB_USER}'@'localhost'`);
    await rootConnection.query(
      `CREATE USER '${APP_DB_USER}'@'localhost' IDENTIFIED WITH mysql_native_password BY '${APP_DB_PASSWORD}'`
    );
    await rootConnection.query(
      `GRANT ALL PRIVILEGES ON \`${APP_DB_NAME}\`.* TO '${APP_DB_USER}'@'localhost'`
    );
    await rootConnection.query('FLUSH PRIVILEGES');
    await rootConnection.query(`USE \`${APP_DB_NAME}\``);
    await executeStatements(rootConnection, TABLE_DEFINITIONS);

    // Schema Migration: Ensure 'year' in Courses supports 'FY'
    try {
      await rootConnection.query("ALTER TABLE Courses MODIFY COLUMN year VARCHAR(10) NOT NULL DEFAULT 'SY'");
      console.log("Schema Migration: Updated Courses.year to VARCHAR(10)");
    } catch (err) {
      // Ignore
    }

    await executeStatements(rootConnection, MIGRATION_STATEMENTS);
    await executeStatements(rootConnection, DATA_SEED_STATEMENTS);

    await fixClassSubjects(rootConnection);
    console.log('Database provisioned.');
  } finally {
    await rootConnection.end();
  }
}

async function fixClassSubjects(connection) {
  try {
    const [classes] = await connection.query('SELECT class_id, year, subjects FROM Classes');
    const [allSubjects] = await connection.query('SELECT subject_id FROM Subjects');
    const subjectIds = allSubjects.map(s => s.subject_id);

    for (const cls of classes) {
      let currentSubjects = [];
      try {
        currentSubjects = typeof cls.subjects === 'string' ? JSON.parse(cls.subjects) : cls.subjects;
      } catch (e) { currentSubjects = []; }

      if (!Array.isArray(currentSubjects) || currentSubjects.length === 0) {
        let count = 0;
        if (cls.year === 'FY') count = 6;
        else if (cls.year === 'SY') count = 5;
        else if (cls.year === 'TY') count = 4;

        if (count > 0 && subjectIds.length > 0) {
          const shuffled = [...subjectIds].sort(() => 0.5 - Math.random());
          const selected = shuffled.slice(0, count);
          await connection.query('UPDATE Classes SET subjects = ? WHERE class_id = ?', [JSON.stringify(selected), cls.class_id]);
          console.log(`Fixed subjects for class ${cls.class_id}`);
        }
      }
    }
  } catch (err) {
    console.error('Error fixing class subjects:', err);
  }
}

