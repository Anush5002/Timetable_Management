const TABLE_DEFINITIONS = [
  `CREATE TABLE IF NOT EXISTS Users (
      user_id INT PRIMARY KEY,
      username VARCHAR(255) NOT NULL,
      password VARCHAR(255) NOT NULL,
      role ENUM('Admin', 'Teacher', 'Student') NOT NULL,
      name VARCHAR(255) NOT NULL,
      email VARCHAR(255) NOT NULL,
      phone VARCHAR(20)
    )`,
  `CREATE TABLE IF NOT EXISTS Courses (
      course_id INT PRIMARY KEY,
      course_name VARCHAR(255) NOT NULL,
      credits INT NOT NULL,
      type ENUM('Lecture', 'Lab', 'Seminar') NOT NULL,
      subject_hours INT NOT NULL,
      year VARCHAR(10) NOT NULL DEFAULT 'SY'
    )`,
  `CREATE TABLE IF NOT EXISTS Subjects (
      subject_id INT PRIMARY KEY,
      course_id INT,
      subject_name VARCHAR(255) NOT NULL,
      hours_per_week INT NOT NULL,
      subject_hours INT,
      type ENUM('Lab', 'Theory', 'Seminar') NOT NULL DEFAULT 'Theory',
      is_elective BOOLEAN DEFAULT FALSE,
      elective_group VARCHAR(50),
      max_seats INT DEFAULT 60,
      lab_required BOOLEAN DEFAULT FALSE,
      lab_equipment JSON,
      FOREIGN KEY (course_id) REFERENCES Courses(course_id)
    )`,
  `CREATE TABLE IF NOT EXISTS Teachers (
      teacher_id INT PRIMARY KEY,
      name VARCHAR(255) NOT NULL,
      max_hours_week INT NOT NULL,
      availability JSON NOT NULL,
      vacation_days JSON NOT NULL
    )`,
  `CREATE TABLE IF NOT EXISTS Students (
      student_id INT PRIMARY KEY,
      name VARCHAR(255) NOT NULL,
      class_id INT,
      enrolled_courses JSON NOT NULL
    )`,
  `CREATE TABLE IF NOT EXISTS Rooms (
      room_id INT PRIMARY KEY,
      room_name VARCHAR(255) NOT NULL,
      capacity INT NOT NULL,
      equipment JSON NOT NULL,
      type ENUM('Lecture', 'Lab') NOT NULL
    )`,
  `CREATE TABLE IF NOT EXISTS Classes (
      class_id INT PRIMARY KEY,
      class_name VARCHAR(50) NOT NULL,
      department VARCHAR(50) NOT NULL,
      year VARCHAR(10) NOT NULL,
      division VARCHAR(5) NOT NULL,
      building VARCHAR(50),
      floor INT,
      room_no VARCHAR(20),
      room_capacity INT DEFAULT 60,
      subjects JSON
    )`,
  `CREATE TABLE IF NOT EXISTS Student_Electives (
      id INT AUTO_INCREMENT PRIMARY KEY,
      student_id INT,
      elective_id INT,
      preference_rank INT,
      status ENUM('chosen', 'enrolled', 'waitlisted', 'rejected') DEFAULT 'chosen',
      timestamp TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
      FOREIGN KEY (student_id) REFERENCES Students(student_id),
      FOREIGN KEY (elective_id) REFERENCES Subjects(subject_id)
    )`,
  `CREATE TABLE IF NOT EXISTS Lab_Groups (
      group_id INT AUTO_INCREMENT PRIMARY KEY,
      lab_id INT,
      subject_id INT,
      group_number INT,
      room_id INT,
      student_ids JSON,
      time_slot VARCHAR(50),
      FOREIGN KEY (subject_id) REFERENCES Subjects(subject_id),
      FOREIGN KEY (room_id) REFERENCES Rooms(room_id)
    )`,
  `CREATE TABLE IF NOT EXISTS Timetable (
      schedule_id INT PRIMARY KEY,
      course_id INT,
      subject_id INT,
      teacher_id INT,
      room_id INT,
      class_id INT,
      day_of_week ENUM('Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday') NOT NULL,
      start_time TIME NOT NULL,
      end_time TIME NOT NULL,
      student_group JSON NOT NULL,
      FOREIGN KEY (course_id) REFERENCES Courses(course_id),
      FOREIGN KEY (subject_id) REFERENCES Subjects(subject_id),
      FOREIGN KEY (teacher_id) REFERENCES Teachers(teacher_id),
      FOREIGN KEY (room_id) REFERENCES Rooms(room_id),
      FOREIGN KEY (class_id) REFERENCES Classes(class_id)
    )`,
  `CREATE TABLE IF NOT EXISTS Constraints (
      constraint_id INT PRIMARY KEY,
      constraint_type VARCHAR(255) NOT NULL,
      details JSON NOT NULL
    )`,
  `CREATE TABLE IF NOT EXISTS Resource_Usage (
      resource_id INT PRIMARY KEY,
      schedule_id INT,
      status ENUM('Available', 'In Use') NOT NULL,
      FOREIGN KEY (schedule_id) REFERENCES Timetable(schedule_id)
    )`,
  `CREATE TABLE IF NOT EXISTS Support_Staff (
      staff_id INT PRIMARY KEY,
      name VARCHAR(255) NOT NULL,
      role ENUM('Technical Support', 'Non-technical Support') NOT NULL
    )`
];

